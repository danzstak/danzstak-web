const { readFileSync } = require('node:fs');
const { join } = require('node:path');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const source = readFileSync(join(__dirname, 'assets/feed-enhancements.js'), 'utf8');
const code = source.slice(source.indexOf('function refreshFeedMediaWorkspace(records)'), source.lastIndexOf('new MutationObserver(records => {'));
const feed = {}, featurePanel = { hidden: false }, featureHeading = { textContent: 'Photos' }, rendered = [];
const context = vm.createContext({ featurePanel, featureHeading, document: { getElementById: () => feed }, renderWorkspace: name => rendered.push(name) });
vm.runInContext(code, context);
context.changes = [{ target: feed, addedNodes: [{}], removedNodes: [] }];
vm.runInContext('refreshFeedMediaWorkspace(changes)', context);
assert.deepEqual(rendered, ['Photos'], 'late feed results refresh the visible gallery');
featureHeading.textContent = 'Videos';
vm.runInContext('refreshFeedMediaWorkspace(changes)', context);
assert.deepEqual(rendered, ['Photos', 'Videos']);
featureHeading.textContent = 'Events';
vm.runInContext('refreshFeedMediaWorkspace(changes)', context);
assert.equal(rendered.length, 2, 'feed refresh does not erase an event draft');
featureHeading.textContent = 'Photos'; featurePanel.hidden = true;
vm.runInContext('refreshFeedMediaWorkspace(changes)', context);
assert.equal(rendered.length, 2, 'hidden workspaces are not rebuilt');
featurePanel.hidden = false;
context.changes = [{ target: {}, addedNodes: [{}], removedNodes: [] }];
vm.runInContext('refreshFeedMediaWorkspace(changes)', context);
assert.equal(rendered.length, 2, 'comments and reactions do not reset the media player');
console.log('Feed media checks passed: late posts refresh galleries without resetting other workspaces.');
