"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const page = fs.readFileSync("record-stores.html", "utf8");
const css = fs.readFileSync("assets/record-stores.css", "utf8");
const placement = fs.readFileSync("assets/record-placement.css", "utf8");
const client = fs.readFileSync("assets/record-stores.js", "utf8");
assert.doesNotMatch(page, /💿/, "the record-store tool must not use a cartoon emoji identity");
assert.match(page, /data-menu-icon="disc"/, "the shared professional record icon should identify the tool");
assert.match(page, /record-stores\.css\?v=2/);
assert.match(page, /record-placement\.css\?v=2/);
assert.match(page, /record-stores\.js\?v=6/);
assert.match(css, /--store-blue:var\(--ds-blue/, "record stores should inherit the shared DANZSTAK tokens");
assert.match(css, /min-height:44px/, "interactive controls need accessible mobile targets");
assert.match(css, /grid-template-columns:repeat\(2,minmax\(0,1fr\)\)/, "desktop results should use available width");
assert.match(css, /@media\(max-width:640px\)[\s\S]*\.store-grid\{grid-template-columns:1fr\}/, "mobile results should become one readable column");
assert.match(placement, /\.placement-controls label:nth-child\(n\+3\)\{grid-column:1\/-1\}/, "long outreach fields should use the full desktop width");
assert.match(client, /store-card-heading/, "result identity should use the compact card hierarchy");
assert.match(client, /Public contact details are not listed/, "missing contacts should be disclosed without fabricated data");
console.log("Record Store design checks passed: shared identity, compact density, responsive cards, and honest contacts.");
