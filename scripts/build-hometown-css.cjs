"use strict";
// Writes the hometown token sets (task 15-A) into assets/epk-looks.css from assets/hometown-looks.js, so the CSS and
// the data never drift. Run: node scripts/build-hometown-css.cjs   (test-hometown-looks.cjs fails if they differ)
const fs = require("node:fs");
const path = require("node:path");
const looks = require("../assets/hometown-looks.js");
const START = "/* hometown-tokens:start (generated by scripts/build-hometown-css.cjs; edit assets/hometown-looks.js) */";
const END = "/* hometown-tokens:end */";

function block() {
  const lines = [START];
  for (const city of looks.CITIES) {
    lines.push(`[data-hometown="${city.id}"]{--home-ground:${city.ground};--home-ink:${city.ink};--home-accent:${city.accent};--home-tint:${city.tint};--home-motif-name:${city.motif}}`);
  }
  // Applied genre x city values are computed by hometown-looks.js (compose) and set inline; print drops textures.
  lines.push("@media print{[data-hometown]{--home-motif:none!important;background-image:none!important}}");
  lines.push(END);
  return lines.join("\n");
}
function render(css) {
  const at = css.indexOf(START), end = css.indexOf(END);
  if (at === -1) return css.replace(/\s*$/, "\n") + block() + "\n";
  return css.slice(0, at) + block() + css.slice(end + END.length);
}
if (require.main === module) {
  const file = path.join(__dirname, "..", "assets", "epk-looks.css");
  fs.writeFileSync(file, render(fs.readFileSync(file, "utf8")));
  console.log(`Wrote ${looks.CITIES.length} hometown token sets to assets/epk-looks.css`);
}
module.exports = { block, render, START, END };
