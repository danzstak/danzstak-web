const { readFileSync } = require('node:fs');
const { join } = require('node:path');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const source = readFileSync(join(__dirname, 'assets/feed-enhancements.js'), 'utf8');
const code = source.slice(source.indexOf('function renderPublishedEvents('), source.indexOf('function renderWorkspace(name)'));
const node = () => ({ children: [], append(...items) { this.children.push(...items); }, appendChild(item) { this.children.push(item); }, replaceChildren() { this.children = []; }, addEventListener(_, handler) { this.click = handler; } });
const list = node(), featurePanel = { hidden: false }, feedView = { hidden: true };
let posts = [], routed = '';
const context = vm.createContext({ list, featurePanel, document: { createElement: node, querySelectorAll: () => posts, getElementById: () => feedView }, history: { replaceState: (_, __, route) => { routed = route; } } });
vm.runInContext(code, context);
vm.runInContext('renderPublishedEvents(list)', context);
assert.equal(list.children[0].textContent, 'No published events yet.');
let focused = false;
posts = [{ id: 'post-event-1', querySelector: selector => ({ textContent: selector === '.post-content' ? '📅 Event: Music meetup' : 'Tomorrow' }), scrollIntoView() {}, focus() { focused = true; } }, { querySelector: () => ({ textContent: 'Ordinary post' }) }];
vm.runInContext('renderPublishedEvents(list)', context);
assert.equal(list.children.length, 1, 'late event replaces empty state and excludes ordinary posts');
const card = list.children[0];
assert.match(card.children[0].textContent, /Music meetup/);
card.children[2].click();
assert.equal(featurePanel.hidden, true);
assert.equal(feedView.hidden, false);
assert.equal(routed, '#post-event-1');
assert.equal(focused, true);
console.log('Published event checks passed: late data replaces empty state and links to the source post.');
